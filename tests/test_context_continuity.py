def test_estimate_tokens():
    # Empty string has 0 tokens
    assert estimate_tokens("") == 0
    # Short sentence
    text = "Hello, what is photosynthesis in class 10 science?"
    tokens = estimate_tokens(text)
    assert 5 <= tokens <= 25
    # Long text roughly scales with characters / subwords
    long_text = "word " * 1000
    long_tokens = estimate_tokens(long_text)
    assert 900 <= long_tokens <= 1500


def test_get_model_spec():
    # Local ollama model
    spec_local = get_model_spec("ollama", "llama3.2:3b")
    assert spec_local.provider == "ollama"
    assert spec_local.context_limit >= 8192
    assert spec_local.model_id == "ollama/llama3.2:3b"

    # Cloud claude model
    spec_claude = get_model_spec("claude", "claude-3-5-sonnet-latest")
    assert spec_claude.provider == "claude"
    assert spec_claude.context_limit >= 200000
    assert spec_claude.model_id == "claude/claude-3-5-sonnet-latest"

    # Fallback for unknown provider/model
    spec_unknown = get_model_spec("custom-provider", "unknown-model")
    assert spec_unknown.context_limit >= 8192


def test_context_budget_pair_preservation():
    # Create 5 pairs of (user, assistant) turns
    history = []
    for i in range(1, 6):
        history.append({
            "role": "user",
            "content": f"Question {i}: Explain concept {i} in great detail."
        })
        history.append({
            "role": "assistant",
            "content": f"Answer {i}: Here is the detailed explanation for concept {i}." * 20,
            "model_id": "ollama/llama3.2:3b"
        })

    spec_large = get_model_spec("claude", "claude-3-5-sonnet-latest")
    # When budget is large, all turns fit
    fitted, truncated, switched = build_context_history(
        history=history,
        spec=spec_large,
        system_tokens=100,
        query_tokens=50,
    )
    assert len(fitted) == 10
    assert truncated is False
    assert switched is True  # history generated by ollama, target is claude

    # When budget is tight (simulate small context window)
    tight_model = ModelSpec(
        provider="test",
        model_name="tight-model",
        context_limit=450,
        max_output=100,
        safety_margin_ratio=0.1,
        tokenizer_type="char_ratio",
        tag="Test",
    )
    fitted_tight, truncated_tight, switched_tight = build_context_history(
        history=history,
        spec=tight_model,
        system_tokens=50,
        query_tokens=30,
    )
    # Must preserve pairs: length must be even and end with assistant
    assert len(fitted_tight) % 2 == 0
    assert len(fitted_tight) < 10
    assert truncated_tight is True
    if fitted_tight:
        assert fitted_tight[0]["role"] == "user"
        assert fitted_tight[-1]["role"] == "assistant"


def test_continuity_notice_injected_on_model_switch():
    # History generated by ollama
    history = [
        {"role": "user", "content": "What is gravity?"},
        {
            "role": "assistant",
            "content": "Gravity is the attractive force between masses.",
            "model_id": "ollama/llama3.2:3b"
        }
    ]

    # Target model is Claude (switch occurred!)
    spec_claude = get_model_spec("claude", "claude-3-5-sonnet-latest")
    fitted, truncated, switched = build_context_history(
        history=history,
        spec=spec_claude,
        system_tokens=100,
        query_tokens=50
    )
    assert switched is True

    messages = build_messages(
        question="Can you give an example?",
        sources=[],
        grade=10,
        language="English",
        history=history,
        provider="claude",
        model_name="claude-3-5-sonnet-latest",
    )

    # Check for continuity notice in the system messages
    sys_contents = [m["content"] for m in messages if m["role"] == "system"]
    found = any(CONTINUITY_NOTICE in c for c in sys_contents)
    assert found is True


