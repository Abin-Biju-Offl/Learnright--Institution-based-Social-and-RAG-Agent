"""
FastAPI Routes for Institutions, Classes, Sections, Role-Specific Invites, and Faculty.
"""

from fastapi import APIRouter, Depends, HTTPException, Query, status
from sqlalchemy.orm import Session

from app.auth.dependencies import (
    get_current_user,
    require_institution_member,
    require_lecturer_or_admin,
    require_org_admin,
)
from app.db.engine import get_db
from app.institution.schemas import (
    ClassAdvisorAssignRequest,
    ClassCreateRequest,
    ClassResponse,
    FacultyMemberResponse,
    InstitutionCreateRequest,
    InstitutionJoinRequest,
    InstitutionResponse,
    InviteAcceptRequest,
    InviteCreateRequest,
    InviteResponse,
    InviteVerifyResponse,
    LecturerProfileUpdateRequest,
    SectionCreateRequest,
    SectionResponse,
    StudentRosterItem,
)
from app.institution.service import InstitutionService

institution_router = APIRouter(prefix="/api", tags=["Institutions"])


# ── Institution Lifecycle ──

@institution_router.post("/institutions", response_model=InstitutionResponse)
def create_institution(
    req: InstitutionCreateRequest,
    current_user: dict = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    """
    Create a new School Institution. The creating user is automatically designated
    as an Organization Administrator (Principal/Headmaster).
    """
    return InstitutionService.create_institution(db, current_user, req)


@institution_router.post("/institutions/join", response_model=InstitutionResponse)
def join_institution(
    req: InstitutionJoinRequest,
    current_user: dict = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    """
    Join an existing institution using its Demo Verification ID / Code.
    """
    return InstitutionService.join_institution(db, current_user, req)


@institution_router.get("/institutions/me")
def get_my_institution(
    current_user: dict = Depends(require_institution_member),
    db: Session = Depends(get_db),
):
    """
    Fetch details of the institution the user belongs to, including all classes,
    sections, student counts, and faculty counts.
    """
    return InstitutionService.get_institution_summary(db, current_user["institution_id"])


# ── Classes & Sections ──

@institution_router.post("/institutions/classes", response_model=ClassResponse)
def create_class(
    req: ClassCreateRequest,
    admin: dict = Depends(require_org_admin),
    db: Session = Depends(get_db),
):
    """
    Create a new Class (e.g. Class 10) under the institution. Restricted to Org Admins.
    """
    inst_id = admin.get("institution_id")
    if not inst_id:
        raise HTTPException(status_code=400, detail="Admin is not affiliated with an institution.")
    return InstitutionService.create_class(db, inst_id, req)


@institution_router.post(
    "/institutions/classes/{class_id}/sections", response_model=SectionResponse
)
def create_section(
    class_id: str,
    req: SectionCreateRequest,
    admin: dict = Depends(require_org_admin),
    db: Session = Depends(get_db),
):
    """
    Create a new Section (e.g. 'A') under the specified class. Restricted to Org Admins.
    """
    inst_id = admin.get("institution_id")
    if not inst_id:
        raise HTTPException(status_code=400, detail="Admin is not affiliated with an institution.")
    return InstitutionService.create_section(db, inst_id, class_id, req)


# ── Role-Specific Invites ──

@institution_router.post("/institutions/invites", response_model=InviteResponse)
def create_invite(
    req: InviteCreateRequest,
    current_user: dict = Depends(require_lecturer_or_admin),
    db: Session = Depends(get_db),
):
    """
    Generate a role-specific invite link:
      - Lecturer Invite: Generated by Org Admin to onboard faculty.
      - Student Invite: Generated by Org Admin or Class Advisor for a specific Class & Section.
    """
    inst_id = current_user.get("institution_id")
    if not inst_id:
        raise HTTPException(status_code=400, detail="User is not affiliated with an institution.")

    # Only Org Admins can generate Lecturer invites
    if req.target_role == "lecturer" and current_user.get("role") != "org_admin":
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Only Organization Administrators can generate Lecturer invite links.",
        )

    return InstitutionService.create_invite(db, inst_id, current_user, req)


@institution_router.get("/invites/{token}/verify", response_model=InviteVerifyResponse)
def verify_invite_token(token: str, db: Session = Depends(get_db)):
    """
    Public validation endpoint for checking invite token validity, school name, and target role.
    """
    return InstitutionService.verify_invite(db, token)


@institution_router.post("/invites/accept")
def accept_invite(
    req: InviteAcceptRequest,
    current_user: dict = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    """
    Accept an invite link and enroll into the institution/section.
    Returns refreshed token pair with updated claims and profile.
    """
    return InstitutionService.accept_invite(db, current_user, req.invite_token)


# ── Faculty & Class Advisor Designation ──

@institution_router.put(
    "/institutions/sections/{section_id}/advisor", response_model=SectionResponse
)
def assign_class_advisor(
    section_id: str,
    req: ClassAdvisorAssignRequest,
    admin: dict = Depends(require_org_admin),
    db: Session = Depends(get_db),
):
    """
    Assign a faculty member as the Class Advisor for a section (null to unassign).
    Restricted to Org Admins.
    """
    inst_id = admin.get("institution_id")
    if not inst_id:
        raise HTTPException(status_code=400, detail="Admin is not affiliated with an institution.")
    return InstitutionService.assign_class_advisor(db, inst_id, section_id, req)


