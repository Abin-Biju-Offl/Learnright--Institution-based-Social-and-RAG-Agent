@institution_router.get(
    "/institutions/students", response_model=list[StudentRosterItem]
)
def list_institution_students(
    class_id: str | None = Query(default=None),
    section_id: str | None = Query(default=None),
    current_user: dict = Depends(require_lecturer_or_admin),
    db: Session = Depends(get_db),
):
    """
    List enrolled students in the institution, optionally filtered by class or section.
    Restricted to Faculty and Administrators.
    """
    return InstitutionService.list_students(
        db, current_user["institution_id"], class_id=class_id, section_id=section_id
    )

