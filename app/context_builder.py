"""
Context Builder: budgets and fits conversation history into the active model's window.

Complies with SKILL.md:
- Section 5.1: Budget calculation per model spec (context limit - max_output - margin - prompt overhead).
- Section 5.2: Selection strategy: always include system prompt + query, add recent turns newest-to-oldest,
  preserve user/assistant pairs (never cut mid-turn).
- Section 5.3: Rolling summary support for turns that exceed budget.
- Section 8: Model switch consistency detection (notices when previous turns were written by a different model).
"""

import math
import re
from typing import Any
from app.registry import ModelSpec, get_model_spec


def estimate_tokens(text: str) -> int:
    """Conservative token estimation (average ~3.6 chars per token with word-boundary awareness)."""
    if not text:
        return 0
    # Fast subword/word heuristic: split by whitespace & punctuation
    words = re.findall(r"\w+|[^\w\s]", text)
    # Most English & Hindi subwords expand to ~1.25x words
    return max(1, math.ceil(len(words) * 1.25))


def calculate_history_budget(
    spec: ModelSpec,
    system_tokens: int,
    query_tokens: int,
    summary_tokens: int = 0,
) -> int:
    """Computes available token budget for history turns per SKILL.md Section 5.1:
    available = context_limit - max_output - safety_margin - system_prompt - query - summary
    """
    safety_margin = int(spec.context_limit * spec.safety_margin_ratio)
    fixed_overhead = spec.max_output + safety_margin + system_tokens + query_tokens + summary_tokens + 100  # template tags
    return max(0, spec.context_limit - fixed_overhead)


def build_context_history(
    history: list[dict[str, Any]] | None,
    spec: ModelSpec,
    system_tokens: int,
    query_tokens: int,
    summary: str | None = None,
) -> tuple[list[dict[str, Any]], bool, bool]:
    """Selects turns from history that fit the active model's budget.

    Returns:
        (selected_turns, was_truncated, different_model_detected)
    """
    if not history:
        return [], False, False

    summary_tokens = estimate_tokens(summary) if summary else 0
    budget = calculate_history_budget(spec, system_tokens, query_tokens, summary_tokens)

    # 1. Group consecutive turns into (user, assistant) or single turns to never cut mid-turn (Section 5.2)
    turns: list[dict[str, Any]] = []
    for turn in history:
        role = turn.get("role")
        content = (turn.get("content") or turn.get("text") or "").strip()
        if role in ("user", "assistant") and content:
            turns.append({
                "role": role,
                "content": content,
                "model_id": turn.get("model_id"),
            })

    if not turns:
        return [], False, False

    # 2. Iterate from newest to oldest, packing turns within budget
    selected_turns: list[dict[str, Any]] = []
    accumulated_tokens = 0
    was_truncated = False
    different_model_detected = False

    # Group into pairs from the end
    idx = len(turns) - 1
    while idx >= 0:
        # Check if this is an assistant turn preceded by a user turn
        if turns[idx]["role"] == "assistant" and idx > 0 and turns[idx - 1]["role"] == "user":
            pair = [turns[idx - 1], turns[idx]]
            idx -= 2
        else:
            pair = [turns[idx]]
            idx -= 1

        pair_tokens = sum(estimate_tokens(m["content"]) + 15 for m in pair)
        if accumulated_tokens + pair_tokens <= budget:
            selected_turns = pair + selected_turns
            accumulated_tokens += pair_tokens
        else:
            was_truncated = True
            break

    # 3. Detect if any assistant message in the selected history was generated by a different model (Section 8)
    active_id = spec.model_id
    for turn in selected_turns:
        if turn["role"] == "assistant":
            m_id = turn.get("model_id")
            if m_id and m_id != active_id:
                different_model_detected = True
                break

    return selected_turns, was_truncated, different_model_detected


def format_rolling_summary(older_turns: list[dict[str, Any]]) -> str:
    """Create a concise data summary of older turns when budget is exceeded (SKILL.md Section 5.3)."""
    if not older_turns:
        return ""
    lines = []
    for turn in older_turns[-8:]:
        role = "Student" if turn.get("role") == "user" else "Tutor"
        text = (turn.get("content") or turn.get("text") or "").strip()
        # Truncate to keep the summary compact
        lines.append(f"- {role}: {text[:140]}")
    return "\n".join(lines)

